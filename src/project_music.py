plusTracks = plusTracks.astype(object)

empty_row = pd.DataFrame([[np.nan]*len(plusTracks.columns)], columns=plusTracks.columns)
plusTracks = pd.concat([empty_row, plusTracks], ignore_index=True)

for j in plusTracks.columns:
    if pd.isna(plusTracks.loc[0, j]):
        plusTracks.loc[0, j] = j

